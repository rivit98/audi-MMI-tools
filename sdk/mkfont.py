#!/usr/bin/env python3
"""mkfont.py - PSF1/PSF2 console font -> C header with a `struct font`.

usage: mkfont.py <font.psf.gz> <c_name> <out.h>

Writes every glyph plus the font's whole unicode map (sorted, BMP only),
for src/audi_stream_receiver/text.h. Unknown characters fall back to the glyph of
'?'. Fonts: sdk/fonts/ (Terminus, SIL OFL 1.1, see OFL.txt).
"""
import gzip
import struct
import sys


def load(path):
    raw = gzip.decompress(open(path, 'rb').read())
    if raw[:2] == b'\x36\x04':
        mode, height = raw[2], raw[3]
        count, width, size, off = (512 if mode & 1 else 256), 8, height, 4
        tab = raw[off + count * size:] if mode & 6 else b''
        cmap, slot, i = {}, 0, 0
        while slot < count and i + 1 < len(tab):
            u = struct.unpack_from('<H', tab, i)[0]
            i += 2
            if u == 0xFFFF:
                slot += 1
            elif u != 0xFFFE:
                cmap.setdefault(u, slot)
    elif raw[:4] == b'\x72\xb5\x4a\x86':
        _, off, flags, count, size, height, width = struct.unpack_from('<7I', raw, 4)
        tab = raw[off + count * size:] if flags & 1 else b''
        cmap = {}
        for slot, entry in enumerate(tab.split(b'\xff')[:count]):
            # only single codepoints; sequences (after 0xFE) are skipped
            for ch in entry.split(b'\xfe')[0].decode('utf-8', 'replace'):
                cmap.setdefault(ord(ch), slot)
    else:
        sys.exit('%s: not a PSF font' % path)
    if not cmap:                       # no table: slot n is codepoint n
        cmap = {c: c for c in range(min(count, 256))}
    row = (width + 7) // 8
    bits = raw[off:off + count * size]
    assert size == row * height, 'unexpected glyph size'
    return width, height, row, count, bits, cmap


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path, name, out = sys.argv[1:]
    w, h, row, count, bits, cmap = load(path)
    cps = sorted(c for c in cmap if c <= 0xFFFF)
    fallback = cmap.get(ord('?'), 0)
    lines = ['/* generated by sdk/mkfont.py from %s - do not edit */' % path.split('/')[-1],
             '#include "text.h"', '',
             'static const uint8_t %s_bits[%d] = {' % (name, len(bits))]
    for i in range(0, len(bits), 16):
        lines.append('\t' + ', '.join('0x%02x' % b for b in bits[i:i + 16]) + ',')
    lines += ['};', '', 'static const uint16_t %s_cp[%d] = {' % (name, len(cps))]
    for i in range(0, len(cps), 12):
        lines.append('\t' + ', '.join('0x%04x' % c for c in cps[i:i + 12]) + ',')
    lines += ['};', '', 'static const uint16_t %s_glyph[%d] = {' % (name, len(cps))]
    for i in range(0, len(cps), 12):
        lines.append('\t' + ', '.join('%d' % cmap[c] for c in cps[i:i + 12]) + ',')
    lines += ['};', '',
              'static const struct font %s = {' % name,
              '\t%d, %d, %d, %s_bits, %s_cp, %s_glyph, %d, %d,' % (
                  w, h, row, name, name, name, len(cps), fallback),
              '};', '']
    with open(out, 'w') as f:
        f.write('\n'.join(lines))
    print('%s: %dx%d, %d glyphs, %d codepoints -> %s' % (name, w, h, count, len(cps), out))


if __name__ == '__main__':
    main()
