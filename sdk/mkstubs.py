#!/usr/bin/env python3
"""
mkstubs.py - build link-time stub sources from stripped QNX shared libraries.

The .so files extracted from the MMI firmware (IFS image) have had their
section headers stripped by mkifs, so GNU ld cannot read their exported
symbols. Their *dynamic segment* is still intact though (the runtime loader
needs it), so we walk it via the program headers:

    PT_DYNAMIC -> DT_SONAME / DT_HASH / DT_SYMTAB / DT_STRTAB

and emit an assembler file that defines every exported symbol with the same
name, binding, type and (for data) size. Assembling it with
`gcc -shared -Wl,-soname,<SONAME>` gives a stub library that is good enough
for the linker: the executable records DT_NEEDED <SONAME>, and on the car the
real library is loaded instead. Data object sizes must match the real ones
because the linker uses them for R_SH_COPY relocations (e.g. errno).

Usage:
    mkstubs.py <lib.so> <out.S>      -> writes stub asm, prints SONAME
    mkstubs.py --list <lib.so>       -> prints the exported symbol table
"""

import struct
import sys

PT_LOAD, PT_DYNAMIC = 1, 2
DT_NULL, DT_HASH, DT_STRTAB, DT_SYMTAB, DT_SONAME = 0, 4, 5, 6, 14
STB_LOCAL, STB_GLOBAL, STB_WEAK = 0, 1, 2
STT_NOTYPE, STT_OBJECT, STT_FUNC = 0, 1, 2
SHN_UNDEF, SHN_ABS = 0, 0xFFF1

# Defined by the linker in every link; a stub must not redefine them.
LINKER_RESERVED = {
    "_DYNAMIC", "_GLOBAL_OFFSET_TABLE_", "_PROCEDURE_LINKAGE_TABLE_",
    "_edata", "edata", "_end", "end", "__end", "__bss_start", "_etext", "etext",
}


class Elf32:
    def __init__(self, data):
        if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 1:
            raise ValueError("not a little-endian ELF32 file")
        self.d = data
        (self.e_phoff,) = struct.unpack_from("<I", data, 28)
        self.e_phentsize, self.e_phnum = struct.unpack_from("<HH", data, 42)
        self.phdrs = [
            struct.unpack_from("<8I", data, self.e_phoff + i * self.e_phentsize)
            for i in range(self.e_phnum)
        ]

    def v2o(self, vaddr):
        """Translate a virtual address to a file offset via the PT_LOAD map."""
        for p_type, p_off, p_vaddr, _pa, p_filesz, _ms, _fl, _al in self.phdrs:
            if p_type == PT_LOAD and p_vaddr <= vaddr < p_vaddr + p_filesz:
                return p_off + (vaddr - p_vaddr)
        raise ValueError("vaddr 0x%x not in any PT_LOAD" % vaddr)

    def dynamic(self):
        dyn = [p for p in self.phdrs if p[0] == PT_DYNAMIC]
        if not dyn:
            raise ValueError("no PT_DYNAMIC (static binary?)")
        off = self.v2o(dyn[0][2])
        tags = {}
        while True:
            tag, val = struct.unpack_from("<iI", self.d, off)
            if tag == DT_NULL:
                break
            tags.setdefault(tag, val)
            off += 8
        return tags

    def cstr(self, off):
        end = self.d.index(b"\0", off)
        return self.d[off:end].decode("latin-1")

    def symbols(self):
        dt = self.dynamic()
        strtab = self.v2o(dt[DT_STRTAB])
        symtab = self.v2o(dt[DT_SYMTAB])
        # DT_HASH = [nbucket, nchain, ...]; nchain == number of symbols
        _nbucket, nchain = struct.unpack_from("<II", self.d, self.v2o(dt[DT_HASH]))
        soname = self.cstr(strtab + dt[DT_SONAME]) if DT_SONAME in dt else None
        syms = []
        for i in range(1, nchain):
            st_name, st_value, st_size, st_info, _other, st_shndx = struct.unpack_from(
                "<IIIBBH", self.d, symtab + i * 16
            )
            name = self.cstr(strtab + st_name)
            bind, typ = st_info >> 4, st_info & 0xF
            if not name or bind == STB_LOCAL or st_shndx == SHN_UNDEF:
                continue
            if name in LINKER_RESERVED:
                continue
            syms.append((name, bind, typ, st_size, st_shndx))
        return soname, syms


def emit_asm(soname, syms):
    out = [
        "/* Link-time stub for %s - generated by mkstubs.py, do not edit. */" % soname,
        "/* Never loaded at runtime: the real library on the MMI is used. */",
    ]
    funcs = [s for s in syms if s[2] != STT_OBJECT]
    objs = [s for s in syms if s[2] == STT_OBJECT]

    out.append("\t.text")
    for name, bind, typ, _size, _shndx in sorted(funcs):
        out.append("\t.%s %s" % ("weak" if bind == STB_WEAK else "globl", name))
        out.append("\t.type %s,@%s" % (name, "function" if typ == STT_FUNC else "notype"))
        out.append("%s:\trts\n\tnop" % name)

    out.append("\t.data\n\t.balign 4")
    for name, bind, _typ, size, _shndx in sorted(objs):
        out.append("\t.%s %s" % ("weak" if bind == STB_WEAK else "globl", name))
        out.append("\t.type %s,@object" % name)
        out.append("\t.size %s,%d" % (name, size))
        out.append("%s:" % name)
        if size:
            out.append("\t.zero %d\n\t.balign 4" % size)
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) == 3 and argv[1] == "--list":
        soname, syms = Elf32(open(argv[2], "rb").read()).symbols()
        kinds = {STT_FUNC: "FUNC", STT_OBJECT: "OBJECT", STT_NOTYPE: "NOTYPE"}
        print("# SONAME %s, %d exported symbols" % (soname, len(syms)))
        for name, bind, typ, size, _shndx in sorted(syms):
            print("%-6s %-6s %6d %s" % (kinds.get(typ, typ), "WEAK" if bind == STB_WEAK else "GLOBAL", size, name))
        return 0
    if len(argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    soname, syms = Elf32(open(argv[1], "rb").read()).symbols()
    if not soname:
        print("error: %s has no DT_SONAME" % argv[1], file=sys.stderr)
        return 1
    with open(argv[2], "w") as f:
        f.write(emit_asm(soname, syms))
    print(soname)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
